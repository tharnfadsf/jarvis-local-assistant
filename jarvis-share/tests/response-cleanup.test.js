'use strict';
// Response cleanup + natural speech (2026-10-14).
//
// Two failures this pins:
//   1. Internal processing notes leaked into user-facing answers, e.g.
//      "... has a duration of 3:42. (analyzed locally with qwen3.5:4b)".
//   2. Written forms were read aloud literally: "**0:09 / 3:42**" reached TTS
//      as "asterisk asterisk zero colon zero nine ...".
//
// The shared layer in jarvis-core.js produces two logically separate outputs:
// display text (clean, readable) and speech text (natural spoken English).
// Both must keep the original meaning, and technical answers, maths, code and
// user-requested literals must survive untouched.
const test = require('node:test');
const assert = require('node:assert/strict');
const core = require('../jarvis-core.js');

const D = t => core.prepareResponse(t);
const S = t => core.prepareResponse(t, { speech: true });

test('internal analysis notes are removed, the answer is kept', () => {
  const input = 'On your screen, you are currently viewing the YouTube Music app. The video playing is by ILLIT, titled Magnetic | Performance, which has a duration of 3:42. (analyzed locally with qwen3.5:4b)';
  const out = D(input);
  assert.ok(!/analy[sz]ed locally/i.test(out), 'annotation must be gone');
  assert.ok(!/qwen/i.test(out), 'model name must be gone');
  assert.ok(!/Magnetic \| Performance/.test(out), 'table pipe cleaned');
  assert.ok(out.includes('Magnetic Performance'), 'useful information preserved');
  assert.ok(out.includes('YouTube Music') && out.includes('ILLIT'), 'meaning preserved');
});

test('equivalent annotations are removed regardless of wording', () => {
  for (const input of [
    'Result (analyzed locally with qwen3.5:4b).',
    'Result (analysed locally with llama3).',
    'Result (processed locally with vision-v2).',
    'Result (generated by the local model).',
    'Result (routed through vision pipeline).',
    'Result (internal).',
    'Result (model: qwen3.5:4b).',
  ]) {
    assert.equal(D(input).replace(/\.$/, ''), 'Result', `should strip: ${input}`);
  }
  // A leading note is removed but the sentence it annotated is kept.
  assert.equal(D('Analyzed locally: the object is a bottle.'), 'the object is a bottle.');
});

test('a genuine answer about an AI model is NOT stripped', () => {
  const input = 'Qwen3.5:4b is a quantized language model that runs locally on your machine.';
  const out = D(input);
  assert.ok(out.includes('Qwen3.5:4b'), 'model name must survive a real explanation');
  assert.ok(out.includes('quantized language model'), 'meaning preserved');
});

test('markdown is cleaned for display but meaningful text is preserved', () => {
  assert.equal(D('**Magnetic** Performance'), 'Magnetic Performance');
  assert.equal(D('__bold__ and _italic_ and ~~draft~~'), 'bold and italic and draft');
  assert.equal(D('# Heading\n- one\n- two'), 'Heading\none\ntwo');
  assert.equal(D('See [the docs](https://example.com) now'), 'See the docs now');
});

test('display text keeps code verbatim', () => {
  const code = '```js\nconst x = 3:42;\n```';
  assert.equal(D(code), code, 'code block must survive display unchanged');
  assert.ok(S(code).includes('const x = 3:42;'), 'code content survives speech');
  assert.ok(!S(code).includes('```'), 'fence markers must never be spoken');
  assert.ok(!S('use `npm run build`').includes('`'), 'backticks must never be spoken');
});

test('speech converts playback timestamps naturally', () => {
  assert.equal(S('**0:09 / 3:42**'), 'nine seconds into a three-minute-and-forty-two-second track');
  assert.equal(S('3:42'), 'three minutes and forty-two seconds');
});

test('speech converts percentages and byte units', () => {
  assert.equal(S('Volume: 50%'), 'Volume: fifty percent');
  assert.equal(S('CPU: 12%'), 'CPU: twelve percent');
  assert.equal(S('RAM: 8.2 GB'), 'RAM: eight point two gigabytes');
});

test('speech names known sites instead of reading URLs', () => {
  assert.equal(S('Open https://music.youtube.com now'), 'Open YouTube Music now');
  assert.equal(S('Go to https://github.com/x'), 'Go to GitHub', 'site named, URL path not read aloud');
  assert.ok(!S('see https://example.org/page').includes('http'), 'bare URL dropped, not read');
});

test('clock times and ratios are not mangled', () => {
  assert.ok(S('Meeting at 7:30 PM').includes('seven thirty'), 'clock time spoken naturally');
  assert.equal(S('The ratio is 16:9'), 'The ratio is 16:9', 'aspect ratio untouched');
  assert.equal(S('Resolution 1920:1080'), 'Resolution 1920:1080', 'large ratio untouched');
});

test('technical, maths and literal answers stay accurate', () => {
  assert.equal(S('The answer is 42.'), 'The answer is 42.');
  assert.equal(S('144 divided by 12 is 12.'), '144 divided by 12 is 12.');
  assert.ok(S('Qwen3.5:4b is a quantized model').includes('Qwen3.5:4b'));
});

test('Thai and mixed Thai-English text is untouched', () => {
  const thai = 'สวัสดีครับ ผมกำลังวิเคราะห์ภาพนี้ (analyzed locally with qwen3.5:4b)';
  assert.ok(S(thai).includes('สวัสดีครับ'), 'Thai preserved');
  assert.ok(!S(thai).includes('analyzed locally'), 'annotation still stripped around Thai');
  assert.equal(D('สวัสดีครับ **bold**'), 'สวัสดีครับ bold', 'markdown cleaned around Thai');
});

test('empty and whitespace input is safe', () => {
  assert.equal(D(''), '');
  assert.equal(S(''), '');
  assert.equal(D('   '), '');
  assert.equal(S(null), '');
  assert.equal(S(undefined), '');
});

test('the app pipeline uses the shared layer for both outputs', () => {
  const fs = require('node:fs');
  const path = require('node:path');
  const app = fs.readFileSync(path.join(__dirname, '..', 'app.js'), 'utf8');
  const speech = app.match(/function forSpeech\(text\) \{[\s\S]*?\n  \}/);
  assert.ok(speech, 'forSpeech must exist');
  assert.ok(speech[0].includes('Core.toNaturalSpeech'), 'speech must use the shared natural-speech layer');
  const display = app.match(/function normalizeResponseText\(text\) \{[\s\S]*?\n  \}/);
  assert.ok(display, 'normalizeResponseText must exist');
  assert.ok(display[0].includes('Core.prepareResponse'), 'display must use the shared cleanup layer');
});

test('numberToWords stays inside its safe range', () => {
  assert.equal(core.numberToWords(0), 'zero');
  assert.equal(core.numberToWords(9), 'nine');
  assert.equal(core.numberToWords(42), 'forty-two');
  assert.equal(core.numberToWords(222), 'two hundred and twenty-two');
  assert.equal(core.numberToWords(342), 'three hundred and forty-two');
  assert.equal(core.numberToWords(1234), 'one thousand two hundred and thirty-four');
  // Beyond range it returns digits rather than guessing.
  assert.equal(core.numberToWords(1000000), '1000000');
});