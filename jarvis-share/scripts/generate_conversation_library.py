def main():
    categories = {}
    # The validator (and chatWithOllama's recent-reply memory) treat a response
    # string as globally unique. Shared one-liners such as "Okay." used to appear
    # in several intents; the final global check then failed. First writer wins,
    # later intents simply lose the shared line - each intent keeps plenty.
    globally_seen = set()
    for category_id, title, intent_id, patterns, responses in INTENTS:
        bucket = categories.setdefault(category_id, {"id": category_id, "title": title, "intents": []})
        bucket["title"] = title if not bucket["intents"] else bucket["title"]
        kept = unique(responses)
        kept = [text for text in kept if not (text in globally_seen or globally_seen.add(text))]
        bucket["intents"].append({"id": intent_id, "patterns": patterns, "responses": kept})
    categories.setdefault("actions", {"id": "actions", "title": "Desktop actions", "intents": []})
    categories["actions"]["intents"].append({
        "id": "app_open_success",
        "patterns": [],
        "responseTemplate": "{app}",
        "responses": LAUNCH,
    })
    # Keep category titles from the first intent in each group.
    titles = {
        "social": "Everyday conversation",
        "daily": "Daily life",
        "entertainment": "Entertainment",
        "casual": "Casual reactions",
        "conversation": "Follow-through",
        "food": "Food",
        "actions": "Desktop actions",
    }
    library = {
        "version": 2,
        "language": "en",
        "categories": [{"id": key, "title": titles.get(key, key), "intents": value["intents"]} for key, value in categories.items()],
    }
    path = ROOT / "conversation-library.json"
    path.write_text(json.dumps(library, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    responses = [r for c in library["categories"] for i in c["intents"] for r in i["responses"]]
    if len(set(responses)) != len(responses) or len(responses) < 1000:
        raise SystemExit(f"Validation failed: {len(set(responses))} unique of {len(responses)}")
    print(f"Wrote {path}: {len(library['categories'])} categories, {sum(len(c['intents']) for c in library['categories'])} intents, {len(responses)} unique responses.")


if __name__ == "__main__":
    main()
